/// Remote identity → framework provenance.
///
/// The skin does not invent an authorization model: it translates the
/// authenticated [SkinPrincipal] into the framework's own [Context]
/// and stamps inbound pulses with it, so every receipt, ledger entry
/// and replayed pulse carries the remote actor's provenance through
/// the framework's existing machinery.
/// {@category Features}
library;

import 'package:cell/cell.dart';

import 'skin_auth.dart';

/// The translation layer that converts external identities into internal
/// framework provenance.
///
/// In the framework's biological metaphor, [ContextBridge] acts as the
/// **Membrane Translator**. It ensures that every **Nervous Signal** (request)
/// arriving at the **Skin Membrane** is stamped with a verified identity
/// before it begins its **Command Journey**.
///
/// ### When to use
/// - **Identity Mapping**: Use this to define how credentials extracted
///   from the wire (like JWTs or API keys) map to the framework's
///   internal security model.
/// - **Provenance Enforcement**: Required to ensure that every
///   **Somatic State Transition** triggered by a remote actor is
///   correctly attributed in the **Forensic Ledger**.
///
/// ### How it works
/// 1. **Signal Ingress**: A [WireRequest] hits the membrane carrying
///    a [SkinPrincipal].
/// 2. **Translation**: The bridge's [resolve] method is called to
///    convert that principal into a framework [Context].
/// 3. **Stamping**: The resulting context is attached to the pulse,
///    becoming the authoritative "who" for the entire journey.
///
/// ### Non‑obvious behavior
/// - **Integrity Gate Prerequisite**: Most **Integrity Gates** within
///   cells rely on the output of this bridge to decide whether to
///   accept or reject a transition.
/// - **Forensic Traceability**: If this bridge is misconfigured, the
///   **Forensic Ledger** will record the wrong provenance, creating
///   a "Forensic Hole" in your audit trail.
/// - **Least Privilege**: By default, the membrane treats incoming
///   signals as untrusted. The bridge is the only way to elevate
///   privilege for a specific journey.
///
/// ### See also
/// - [SkinPrincipal]: The external identity being translated.
/// - [Context]: The internal provenance record.
/// - [SkinAuth]: The mechanism that provides the principal to this bridge.
abstract interface class ContextBridge {
  /// Maps a verified [principal] to a framework [Context].
  ///
  /// This method defines the "Identity DNA" for a specific
  /// **Command Journey**. It determines what level of authority
  /// the signal carries as it travels toward a cell.
  Context resolve(SkinPrincipal principal);
}

/// The default translator that stamps signals with a descriptive identity.
///
/// In the framework's biological metaphor, [DescribeContextBridge] is the
/// **Basic Identity Stamper**. It provides a simple **External Echo** by
/// taking the external [SkinPrincipal]'s traits—its ID and roles—and
/// encoding them directly into the framework's provenance description.
///
/// ### When to use
/// - **Default Integration**: The standard choice when you want the
///   **Forensic Ledger** to record the remote actor's ID without
///   mapping to a complex internal permission system.
/// - **Debugging & Auditing**: Useful when you need a human-readable
///   string in the ledger that clearly indicates the signal originated
///   from the **Skin Membrane**.
///
/// ### How it works
/// 1. **Signal Tagging**: It reads the [SkinPrincipal.id] and [SkinPrincipal.roles].
/// 2. **Provenance Formatting**: It constructs a string prefixed with `skin:`.
/// 3. **Context Creation**: It returns a [Context.describe] object, which
///    becomes the "Who" for the resulting **Command Journey**.
///
/// ### Non‑obvious behavior
/// - **Least Privilege**: While it provides identity, it does not
///   grant special framework powers. The resulting [Context] is
///   treated as a standard external actor by most **Integrity Gates**.
/// - **String-Based Identity**: Because this bridge relies on
///   [Context.describe], it is optimized for logging and auditing.
///   If your cells require structural identity checks (like `Context.system`),
///   use a specialized bridge instead.
/// - **Transparency**: Every **Forensic Receipt** generated by a signal
///   processed by this bridge will explicitly show the principal's
///   roles in its provenance record.
///
/// ### See also
/// - [Context.describe]: The internal provenance type created by this bridge.
/// - [SystemContextBridge]: A bridge that grants full authority.
final class DescribeContextBridge implements ContextBridge {
  const DescribeContextBridge();

  @override
  Context resolve(SkinPrincipal principal) => Context.describe(
        'skin:${principal.id}'
        '${principal.roles.isEmpty ? '' : ' roles=${principal.roles.join(',')}'}',
      );
}

/// A bridge that resolves every incoming signal's **base** context to
/// [Context.system].
///
/// In the framework's biological metaphor, [SystemContextBridge] is the
/// **Somatic Override**. It ignores the specific traits of the external
/// [SkinPrincipal] and stamps the **Command Journey**'s base context
/// with the system's own "DNA" ([Context.system]).
///
/// ### When to use
/// - **Trusted Automation**: Use this for internal scripts, administrative
///   tools, or trusted proxies where the **Skin Membrane** should not
///   impose identity-based restrictions.
/// - **System-to-System Bridges**: Ideal for linking two different cell
///   clusters where the bridge itself is considered a part of the
///   authorized nervous system.
///
/// ### How it works
/// 1. **Signal Ingress**: A [WireRequest] arrives.
/// 2. **Base Elevation**: The bridge ignores the credentials provided
///    by [SkinAuth] and resolves to [Context.system].
/// 3. **Principal Still On Top**: the request context's own `actor`
///    remains `skin:<principal id>` (the REST adapter always stamps
///    `skinPulseContext`), and the principal snapshot still rides in
///    `others['skin.principal']`. A gate that reads only
///    `SkinCall.current!.pulseContext.actor` sees the principal, not
///    `system`; a gate that reads the base context sees `Context.system`.
///
/// ### Non‑obvious behavior
/// - **Does not skip the domain gate**: a refusing `TestCell` still
///   rejects the apply — system authority is provenance, not a bypass.
/// - **Forensic Visibility**: The ledger row still carries the
///   `skin:<principal id>` actor from the pulse the binding returned;
///   the system base is part of the stored context lineage.
/// - **Security Risk**: This bridge marks every request as
///   system-based provenance. It should only be used over physically
///   secured or highly trusted transport layers.
/// - **Authority Persistence**: Any cell mutation triggered via this
///   bridge carries the system base context.
///
/// ### See also
/// - [Context.system]: The high-authority base context being granted.
/// - [DescribeContextBridge]: A safer alternative that preserves external identity.
final class SystemContextBridge implements ContextBridge {
  /// Creates a new [SystemContextBridge] to grant a system base context.
  const SystemContextBridge();

  /// Resolves any [principal] to the authoritative [Context.system].
  ///
  /// In the biological metaphor, this replaces the signal's external
  /// signature with the system's internal somatic signature.
  @override
  Context resolve(SkinPrincipal principal) => Context.system;
}
