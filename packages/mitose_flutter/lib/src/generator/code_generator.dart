GeneratedFile _generateScreen(
  BrdScreen screen,
  Brd brd,
  Map<String, WidgetChoice> choices,
) {
  final screenChoices = [
    for (final req in brd.requirements.where((r) => r.screen == screen.name))
      choices[req.id]!,
  ];
  final boundNames = _boundNames(brd, screen.name);
  final isFirstScreen = brd.screens.first.name == screen.name;
  final localStates = [
    for (final state in brd.state)
      if (!state.appLevel &&
          (boundNames.contains(state.name) ||
              // Unbound screen-local states (e.g. a new-todo input)
              // land on the first screen in v0.1.
              (isFirstScreen && !_boundAnywhere(brd, state.name))))
        state,
  ];
  final appLevelUsed = <String>{
    for (final choice in screenChoices)
      for (final state in choice.boundStates)
        if (state.appLevel) state.name,
  }.toList();
  // Every cell the screen touches is resolved from the scope so tests
  // can inject it; app-level cells keep their imports for model types.
  final ownedStates = [
    ...localStates,
    for (final name in appLevelUsed) brd.stateByName(name)!,
  ];

  final buffer = StringBuffer()
    ..writeln('// Generated by mitose_flutter. Do not edit by hand —')
    ..writeln('// re-run the pipeline and review the diff instead.')
    ..writeln();
  if (screenChoices.any((c) => c.extra['debounce'] == true)) {
    buffer
      ..writeln("import 'dart:async';")
      ..writeln();
  }
  buffer
    ..writeln("import 'package:cell_flutter/cell_flutter.dart';")
    ..writeln("import 'package:flutter/material.dart';")
    ..writeln();
  for (final cell in appLevelUsed) {
    buffer.writeln("import '../cells/${cellFileName(cell)}';");
  }
  final navigationTarget = screenChoices
      .where((c) => c.extra.containsKey('targetScreen'))
      .map((c) => c.extra['targetScreen'] as String)
      .firstOrNull;
  if (navigationTarget != null) {
    buffer.writeln("import '${screenFileName(navigationTarget)}';");
  }
  buffer
    ..writeln()
    ..writeln('/// The ${screen.name} screen.')
    ..writeln(
        'class ${screenClassName(screen.name)} extends ${ownedStates.isEmpty ? 'StatelessWidget' : 'StatefulWidget'} {')
    ..writeln('  const ${screenClassName(screen.name)}({super.key});');

  if (ownedStates.isEmpty) {
    buffer
      ..writeln()
      ..writeln('  @override')
      ..writeln('  Widget build(BuildContext context) {');
    _emitBody(buffer, screen, screenChoices, const [], brd);
    buffer
      ..writeln('  }')
      ..writeln('}');
  } else {
    buffer
      ..writeln()
      ..writeln('  @override')
      ..writeln('  State<${screenClassName(screen.name)}> createState() =>')
      ..writeln('      _${screenClassName(screen.name)}State();')
      ..writeln('}')
      ..writeln()
      ..writeln('class _${screenClassName(screen.name)}State')
      ..writeln('    extends State<${screenClassName(screen.name)}> {');
    for (final state in ownedStates) {
      buffer.writeln('  late final ValueCell<${state.type}> ${state.name};');
    }
    if (screenChoices.any((c) => c.extra.containsKey('targetScreen'))) {
      buffer.writeln('  String? _errorMessage;');
    }
    buffer
      ..writeln()
      ..writeln('  @override')
      ..writeln('  void didChangeDependencies() {')
      ..writeln('    super.didChangeDependencies();');
    for (final state in ownedStates) {
      buffer.writeln(
          '    ${state.name} = CellScope.valueOf<${state.type}>(context, #${state.name});');
    }
    buffer
      ..writeln('  }')
      ..writeln()
      ..writeln('  @override')
      ..writeln('  Widget build(BuildContext context) {');
    _emitBody(buffer, screen, screenChoices, ownedStates, brd);
    buffer.writeln('  }');
    _emitHelpers(buffer, screenChoices, ownedStates);
    buffer.writeln('}');
  }
  return GeneratedFile(
      path: 'lib/screens/${screenFileName(screen.name)}',
      content: buffer.toString());
}

void _emitBody(
  StringBuffer buffer,
  BrdScreen screen,
  List<WidgetChoice> choices,
  List<BrdState> ownedStates,
  Brd brd,
) {
  final children = <String>[];

  // Form validation errors (set by the audit listener).
  if (choices.any((c) => c.extra.containsKey('targetScreen'))) {
    children.add('if (_errorMessage != null) Text(_errorMessage!),');
  }

  // Text fields (FormPattern).
  final textFields = choices.where((c) => c.widget == 'CellTextField');
  for (final choice in textFields) {
    final state = choice.boundStates.first;
    final label = _titleCase(state.name);
    children.add('CellTextField(\n'
        '  cell: ${state.name},\n'
        "  decoration: const InputDecoration(labelText: '$label'),\n"
        '),');
  }

  // Lists (DisplayPattern with list flag).
  for (final choice in choices.where((c) => c.widget == 'CellListView')) {
    final state = choice.boundStates.first;
    final hasDelete = choices.any((c) => c.extra['listAction'] == 'delete');
    final listView = 'CellListView<${_itemType(state.type)}>.builder(\n'
        '  cell: ${state.name},\n'
        '  itemBuilder: (context, item, index) {\n'
        '${hasDelete ? _dismissibleItem(state) : '    return ListTile(title: Text(item.toString()));'}\n'
        '  },\n'
        ')';
    // The screen body is a Column; give the list bounded height.
    children.add('Expanded(\n  child: $listView,\n),');
  }

  // Async builders (merged per async state).
  final asyncByState = <String, List<WidgetChoice>>{};
  for (final choice in choices.where((c) => c.widget == 'CellAsyncBuilder')) {
    asyncByState
        .putIfAbsent(choice.boundStates.first.name, () => [])
        .add(choice);
  }
  for (final entry in asyncByState.entries) {
    final state = brd.stateByName(entry.key)!;
    final loading = entry.value
            .map((c) => c.pattern)
            .whereType<AsyncPattern>()
            .map((p) => p.loadingText)
            .firstOrNull ??
        'Loading...';
    final error = entry.value
        .map((c) => c.extra['errorText'] as String?)
        .whereType<String>()
        .firstOrNull;
    final empty = entry.value
        .map((c) => c.extra['emptyText'] as String?)
        .whereType<String>()
        .firstOrNull;
    children.add(_asyncBuilder(state, loading, error, empty));
  }

  // Submit button + listener (form interaction).
  final submitChoice =
      choices.where((c) => c.extra.containsKey('targetScreen')).firstOrNull;
  if (submitChoice != null) {
    final trigger = submitChoice.requirement.trigger ?? 'tap Submit';
    final buttonText =
        RegExp(r'^(?:tap|press) (.+)$').firstMatch(trigger)?.group(1) ??
            'Submit';
    final submitState =
        submitChoice.boundStates.firstWhere((s) => s.name == 'submit');
    children.add('ElevatedButton(\n'
        '  onPressed: () => ${submitState.name}.value = true,\n'
        "  child: Text('$buttonText'),\n"
        '),');
    children.add('CellListener(\n'
        '  cell: ${submitState.name},\n'
        '  onPulse: (context, pulse) {\n'
        '    if (pulse.payload == true) {\n'
        '      _signIn(context);\n'
        '    }\n'
        '  },\n'
        '  child: const SizedBox.shrink(),\n'
        '),');
  }

  // List action buttons.
  final hasAdd = choices.any((c) => c.extra['listAction'] == 'add');
  if (hasAdd) {
    final input = ownedStates.where((s) => s.type == 'String').firstOrNull;
    if (input != null) {
      children.add('CellTextField(\n'
          '  cell: ${input.name},\n'
          "  decoration: const InputDecoration(labelText: 'Todo'),\n"
          '),');
    }
  }
  for (final choice in choices.where((c) =>
      c.extra.containsKey('listAction') && c.extra['listAction'] != 'delete')) {
    final action = choice.extra['listAction'] as String;
    if (action == 'add') {
      children.add('ElevatedButton(\n'
          '  onPressed: () => _addTodo(),\n'
          "  child: const Text('Add'),\n"
          '),');
    } else if (action == 'reorder') {
      children.add('IconButton(\n'
          '  tooltip: \'Reorder\',\n'
          '  icon: const Icon(Icons.swap_vert),\n'
          '  onPressed: () => _reorderTodo(),\n'
          '),');
    }
  }

  // Debounce listener.
  final debounceChoice =
      choices.where((c) => c.extra['debounce'] == true).firstOrNull;
  if (debounceChoice != null) {
    final field = debounceChoice.boundStates.first;
    children.add('CellListener(\n'
        '  cell: ${field.name},\n'
        '  onPulse: (context, pulse) => _debouncedSearch(),\n'
        '  child: const SizedBox.shrink(),\n'
        '),');
  }

  // Retry button.
  if (choices.any((c) => c.extra['retry'] == true)) {
    children.add('TextButton(\n'
        '  onPressed: () => _retry(),\n'
        "  child: const Text('Retry'),\n"
        '),');
  }

  final body = children.isEmpty
      ? 'const SizedBox.shrink()'
      : 'Column(\n'
          '  children: [\n'
          '${children.map((c) => c.split('\n').map((l) => '    $l').join('\n')).join('\n')}\n'
          '  ],\n'
          ')';

  buffer
    ..writeln('    return Scaffold(')
    ..writeln("      appBar: AppBar(title: const Text('${screen.name}')),")
    ..writeln('      body: CellErrorBoundary(')
    ..writeln("        onError: (error, stack) => Text('\$error'),")
    ..writeln('        child: $body,')
    ..writeln('      ),')
    ..writeln('    );');
}

String _dismissibleItem(BrdState state) {
  return '    return Dismissible(\n'
      '      key: ValueKey(item),\n'
      '      onDismissed: (direction) => _deleteTodo(item),\n'
      '      child: ListTile(title: Text(item.toString())),\n'
      '    );';
}

String _asyncBuilder(
  BrdState state,
  String loading,
  String? error,
  String? empty,
) {
  final buffer = StringBuffer()
    ..writeln('CellAsyncBuilder<${state.type}>(')
    ..writeln('  cell: ${state.name},')
    ..writeln('  builder: (context, snapshot) {')
    ..writeln('    final data = snapshot.data ??')
    ..writeln('        ${state.name}.value ??')
    ..writeln('        ${_asyncSeed(state)};')
    ..writeln('    if (data.asyncValue.isLoading) {')
    ..writeln("      return const Text('$loading');")
    ..writeln('    }');
  if (error != null) {
    buffer
      ..writeln('    if (data.asyncValue.hasError) {')
      ..writeln(
          "      return Text(data.asyncValue.error?.toString() ?? '$error');")
      ..writeln('    }');
  }
  if (empty != null) {
    buffer
      ..writeln('    if (data.asyncValue.isEmpty) {')
      ..writeln("      return const Text('$empty');")
      ..writeln('    }');
  }
  buffer
    ..writeln('    final value = data.asyncValue.value;')
    ..writeln(
        "    return Text(value is List ? value.first.toString() : '\$value');")
    ..writeln('  },')
    ..writeln('),');
  return buffer.toString();
}

String _asyncSeed(BrdState state) => _normalizedInitial(state);

void _emitHelpers(
  StringBuffer buffer,
  List<WidgetChoice> choices,
  List<BrdState> ownedStates,
) {
  if (choices.any((c) => c.extra.containsKey('targetScreen'))) {
    final email = ownedStates.where((s) => s.name == 'email').firstOrNull;
    final password = ownedStates.where((s) => s.name == 'password').firstOrNull;
    final authState = _boundState(choices, 'auth');
    buffer.writeln('  void _signIn(BuildContext context) {');
    if (email != null) {
      buffer.writeln('    final emailValue = ${email.name}.value;');
      if (password != null) {
        buffer.writeln('    final passwordValue = ${password.name}.value;');
      }
    } else {
      buffer.writeln("    const emailValue = 'missing';");
    }
    buffer
      ..writeln('    if (emailValue == null || emailValue.isEmpty) {')
      ..writeln("      setState(() => _errorMessage = 'Email is required');")
      ..writeln('      return;')
      ..writeln('    }')
      ..writeln("    if (!emailValue.contains('@')) {")
      ..writeln("      setState(() => _errorMessage = 'Invalid email');")
      ..writeln('      return;')
      ..writeln('    }');
    if (password != null) {
      buffer
        ..writeln('    if (passwordValue == null || passwordValue.isEmpty) {')
        ..writeln(
            "      setState(() => _errorMessage = 'Password is required');")
        ..writeln('      return;')
        ..writeln('    }');
    }
    if (authState != null) {
      buffer.writeln('    ${authState.name}.value = AuthState.signedIn;');
    }
    buffer
      ..writeln('    Navigator.of(context).push(')
      ..writeln('      MaterialPageRoute<void>(builder: (context) =>')
      ..writeln('          const HomeScreen()),')
      ..writeln('    );')
      ..writeln('  }')
      ..writeln();
  }
  if (choices.any((c) => c.extra['listAction'] == 'add')) {
    final list = brdListState(choices);
    final field = ownedStates.where((s) => s.type == 'String').firstOrNull;
    buffer.writeln('  void _addTodo() {');
    if (list != null && field != null) {
      buffer
        ..writeln('    final current = '
            'List<Todo>.of(${list.name}.value ?? const []);')
        ..writeln("    current.add(Todo(${field.name}.value ?? ''));")
        ..writeln('    ${list.name}.value = current;')
        ..writeln("    ${field.name}.value = '';");
    } else {
      buffer.writeln('    // No list cell to add to (empty BRD shape).');
    }
    buffer
      ..writeln('  }')
      ..writeln();
  }
  if (choices.any((c) => c.extra['listAction'] == 'delete')) {
    final list = brdListState(choices)!;
    buffer
      ..writeln('  void _deleteTodo(Todo item) {')
      ..writeln(
          '    final current = List<Todo>.of(${list.name}.value ?? const []);')
      ..writeln('    current.remove(item);')
      ..writeln('    ${list.name}.value = current;')
      ..writeln('  }')
      ..writeln();
  }
  if (choices.any((c) => c.extra['listAction'] == 'reorder')) {
    final list = brdListState(choices)!;
    buffer
      ..writeln('  void _reorderTodo() {')
      ..writeln(
          '    final current = List<Todo>.of(${list.name}.value ?? const []);')
      ..writeln('    if (current.length > 1) {')
      ..writeln('      final first = current.removeAt(0);')
      ..writeln('      current.add(first);')
      ..writeln('      ${list.name}.value = current;')
      ..writeln('    }')
      ..writeln('  }')
      ..writeln();
  }
  if (choices.any((c) => c.extra['debounce'] == true)) {
    final asyncState = asyncStateOf(choices);
    final expr = asyncState != null ? asyncState.name : 'searchResults';
    final type = asyncState?.type ?? 'SearchResult';
    buffer
      ..writeln('  void _debouncedSearch() {')
      ..writeln('    $expr.value =')
      ..writeln('        $type(AsyncValue.loading());')
      ..writeln('    Timer(const Duration(milliseconds: 300), () {')
      ..writeln('      $expr.value =')
      ..writeln("          $type(AsyncValue.data(['result one']));")
      ..writeln('    });')
      ..writeln('  }')
      ..writeln();
  }
  if (choices.any((c) => c.extra['retry'] == true)) {
    final asyncState = asyncStateOf(choices);
    final expr = asyncState != null ? asyncState.name : 'searchResults';
    final type = asyncState?.type ?? 'SearchResult';
    buffer
      ..writeln('  void _retry() {')
      ..writeln('    $expr.value =')
      ..writeln('        $type(AsyncValue.loading());')
      ..writeln('  }')
      ..writeln();
  }
}

BrdState? _boundState(List<WidgetChoice> choices, String name) {
  for (final choice in choices) {
    for (final state in choice.boundStates) {
      if (state.name == name) return state;
    }
  }
  return null;
}

/// The cell expression for [state]: restorable states ARE ValueCells
/// (used directly); `Cell.state` handles expose `.cell`.
String _cellExpr(BrdState state) =>
    state.restorable ? state.name : '${state.name}.cell';

BrdState? brdListState(List<WidgetChoice> choices) {
  for (final choice in choices) {
    for (final state in choice.boundStates) {
      if (state.isListType) return state;
    }
  }
  return null;
}

BrdState? asyncStateOf(List<WidgetChoice> choices) {
  for (final choice in choices) {
    for (final state in choice.boundStates) {
      if ((state.initial ?? '').contains('AsyncValue')) return state;
    }
  }
  return null;
}

String _itemType(String listType) =>
    RegExp(r'^List<(.+)>$').firstMatch(listType)?.group(1) ?? 'Object';

String _titleCase(String name) =>
    '${name[0].toUpperCase()}${name.substring(1)}';

