List<GeneratedFile> _generateCells(Brd brd) {
  final files = <GeneratedFile>[];
  final declaredModels = <String>{};
  for (final state in brd.state.where((s) => s.appLevel)) {
    files.add(GeneratedFile(
      path: 'lib/cells/${cellFileName(state.name)}',
      content: _cellFile(state, brd, declaredModels),
    ));
  }
  return files;
}

String _cellFile(BrdState state, Brd brd, Set<String> declaredModels) {
  final buffer = StringBuffer()
    ..writeln('// Generated by mitose_flutter. Do not edit by hand —')
    ..writeln('// re-run the pipeline and review the diff instead.')
    ..writeln()
    ..writeln("import 'package:cell_flutter/cell_flutter.dart';")
    ..writeln();

  final models = _modelsFor(state, brd, declaredModels);
  if (models != null) {
    buffer
      ..writeln(models)
      ..writeln();
  }

  final initial = _normalizedInitial(state);
  if (state.restorable) {
    buffer.writeln('/// The restorable cell backing #${state.name}.');
    buffer.writeln('final ${state.name} = restorableState<${state.type}>(');
    buffer.writeln("  restorationId: '${state.name}',");
    buffer.writeln('  initial: $initial,');
    final codecs = _codecsFor(state);
    if (codecs != null) {
      buffer.writeln(codecs);
    }
    buffer.writeln(');');
  } else {
    buffer.writeln('/// The app-level cell backing #${state.name}.');
    buffer.writeln('final ${state.name} = Cell.state<${state.type}>(');
    buffer.writeln('  initial: $initial,');
    buffer.writeln(');');
  }
  return buffer.toString();
}

/// The synthesized model types for [state]'s custom types.
String? _modelsFor(BrdState state, Brd brd, Set<String> declaredModels) {
  final buffer = StringBuffer();
  final bare = bareTypeName(state.type);

  // AsyncValue helper when the initial references it.
  final initial = state.initial ?? '';
  if (initial.contains('AsyncValue') &&
      !declaredModels.contains('AsyncValue')) {
    declaredModels.add('AsyncValue');
    buffer.writeln('/// The async state wrapper the generated app renders.');
    buffer.writeln('class AsyncValue {');
    buffer.writeln('  const AsyncValue.loading()');
    buffer.writeln(
        '      : value = null, error = null, isLoading = true, hasError = false;');
    buffer.writeln('  const AsyncValue.data(this.value)');
    buffer
        .writeln('      : error = null, isLoading = false, hasError = false;');
    buffer.writeln('  const AsyncValue.error(this.error)');
    buffer.writeln('      : value = null, isLoading = false, hasError = true;');
    buffer.writeln('  final Object? value;');
    buffer.writeln('  final Object? error;');
    buffer.writeln('  final bool isLoading;');
    buffer.writeln('  final bool hasError;');
    buffer.writeln('  bool get isEmpty =>');
    buffer.writeln('      value == null ||');
    buffer.writeln('      (value is String && (value as String).isEmpty) ||');
    buffer.writeln('      (value is List && (value as List).isEmpty);');
    buffer.writeln('}');
    buffer.writeln();
  }

  // An enum for initials of the form `Type.member`.
  if (!isBuiltin(bare) && !declaredModels.contains(bare)) {
    final memberMatch = RegExp(r'^(\w+)\.(\w+)$').firstMatch(initial);
    if (memberMatch != null && memberMatch.group(1) == bare) {
      declaredModels.add(bare);
      final member = memberMatch.group(2)!;
      final second = member == 'signedOut' ? 'signedIn' : 'other';
      buffer.writeln('/// The states the generated app distinguishes.');
      buffer.writeln('enum $bare { $member, $second }');
      buffer.writeln();
    } else if (state.type.startsWith('List<')) {
      final item = RegExp(r'^List<(.+)>$').firstMatch(state.type)!.group(1)!;
      if (!isBuiltin(item) && !declaredModels.contains(item)) {
        declaredModels.add(item);
        buffer.writeln('/// A generated list item model.');
        buffer.writeln('class $item {');
        buffer.writeln('  const $item(this.title);');
        buffer.writeln('  final String title;');
        buffer.writeln('  @override');
        buffer.writeln('  String toString() => title;');
        buffer.writeln('}');
        buffer.writeln();
      }
    } else {
      declaredModels.add(bare);
      buffer.writeln('/// A generated model wrapping the async value.');
      buffer.writeln('class $bare {');
      buffer.writeln('  const $bare(this.asyncValue);');
      buffer.writeln('  final AsyncValue asyncValue;');
      buffer.writeln('  @override');
      buffer.writeln("  String toString() => '\${asyncValue.value ?? ''}';");
      buffer.writeln('}');
      buffer.writeln();
    }
  }

  return buffer.isEmpty ? null : buffer.toString();
}

/// Restoration codecs for custom restorable types.
String? _codecsFor(BrdState state) {
  final bare = bareTypeName(state.type);
  final initial = state.initial ?? '';
  if (RegExp(r'^List<').hasMatch(state.type)) {
    final item = RegExp(r'^List<(.+)>$').firstMatch(state.type)!.group(1)!;
    return '  toPrimitives: (value) => value?.map((item) => item.title).toList(),\n'
        '  fromPrimitives: (data) => (data as List? ?? const [])\n'
        "      .map((title) => $item('\$title'))\n"
        '      .toList(),';
  }
  if (RegExp(r'^\w+\.\w+$').hasMatch(initial) &&
      initial.split('.').first == bare) {
    final fallback = initial.split('.').last;
    return '  toPrimitives: (value) => value?.name,\n'
        '  fromPrimitives: (data) => $bare.values.firstWhere(\n'
        '    (value) => value.name == data,\n'
        '    orElse: () => $bare.$fallback,\n'
        '  ),';
  }
  return null;
}

/// Wraps `AsyncValue.loading` into `SearchResult(AsyncValue.loading())`.
String _normalizedInitial(BrdState state) {
  final initial = state.initial ?? 'null';
  final typeName = RegExp(r'^[A-Za-z_]\w*').firstMatch(state.type)?.group(0);
  final initialRoot = RegExp(r'^[A-Za-z_]\w*').firstMatch(initial)?.group(0);
  if (typeName != null &&
      initialRoot != null &&
      typeName != initialRoot &&
      RegExp(r'^[A-Z]').hasMatch(typeName)) {
    final parens = initial.endsWith(')') ? initial : '$initial()';
    return '$typeName($parens)';
  }
  return initial;
}

