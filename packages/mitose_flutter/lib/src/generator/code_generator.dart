GeneratedFile _generateMain(Brd brd) {
  final appLevel = brd.state.where((s) => s.appLevel).toList();
  final anyRestorable = brd.state.any((s) => s.restorable);

  final buffer = StringBuffer()
    ..writeln('// Generated by mitose_flutter. Do not edit by hand —')
    ..writeln('// re-run the pipeline and review the diff instead.')
    ..writeln()
    ..writeln("import 'package:cell_flutter/cell_flutter.dart';")
    ..writeln("import 'package:flutter/material.dart';")
    ..writeln();
  for (final cell in appLevel) {
    buffer.writeln("import 'cells/${cellFileName(cell.name)}';");
  }
  for (final screen in brd.screens) {
    buffer.writeln("import 'screens/${screenFileName(screen.name)}';");
  }
  buffer
    ..writeln()
    ..writeln('void main() {')
    ..writeln('  runApp(const App());')
    ..writeln('}')
    ..writeln()
    ..writeln('/// The generated app root.')
    ..writeln('class App extends StatelessWidget {')
    ..writeln('  const App({super.key});')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  Widget build(BuildContext context) {')
    ..writeln('    final app = MaterialApp(')
    ..writeln("      title: '${brd.title}',")
    ..writeln("      initialRoute: '${brd.screens.first.route}',")
    ..writeln('      routes: {');
  for (final screen in brd.screens) {
    buffer.writeln(
        "        '${screen.route}': (context) => const ${screenClassName(screen.name)}(),");
  }
  buffer.writeln('      },');
  buffer.writeln('    );');

  final material = anyRestorable
      ? '    final scoped = CellRestorationScope(\n'
          "      restorationScopeId: 'app',\n"
          '      child: app,\n'
          '    );\n'
      : '    final scoped = app;\n';

  final scopeCells = '    final tree = CellScope(\n'
      '      cells: {\n'
      '${appLevel.map((c) => "        #${c.name}: ${_cellExpr(c)},").join('\n')}\n'
      '      },\n'
      '      child: scoped,\n'
      '    );\n';

  buffer
    ..write(material)
    ..write(scopeCells)
    ..writeln()
    ..writeln('    return CellErrorBoundary(')
    ..writeln('      onError: (error, stack) => Scaffold(')
    ..writeln('        body: Center(child: Text(\'Error: \$error\')),')
    ..writeln('      ),')
    ..writeln('      child: tree,')
    ..writeln('    );')
    ..writeln('  }')
    ..writeln('}');

  return GeneratedFile(path: 'lib/main.dart', content: buffer.toString());
}

