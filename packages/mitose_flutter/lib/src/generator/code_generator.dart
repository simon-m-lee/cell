import 'generated_app.dart';

/// Generates the complete app tree for [brd].
GeneratedApp generateApp(Brd brd) {
  final files = <GeneratedFile>[];
  final choices = {
    for (final req in brd.requirements) req.id: place(req, brd),
  };

  files.addAll(_generateCells(brd));
  files.add(_generateMain(brd));
  for (final screen in brd.screens) {
    files.add(_generateScreen(screen, brd, choices));
  }
  files.add(_generatePubspec(brd));
  files.add(_generateAnalysisOptions());
  files.add(_generateReadme(brd));

  return GeneratedApp(brdTitle: brd.title, files: files);
}

/// The bound state names for one screen (from its requirements).
List<String> _boundNames(Brd brd, String screen) {
  final names = <String>[];
  for (final req in brd.requirements.where((r) => r.screen == screen)) {
    for (final state in place(req, brd).boundStates) {
      if (!names.contains(state.name)) names.add(state.name);
    }
  }
  return names;
}

/// Whether any requirement binds [name].
bool _boundAnywhere(Brd brd, String name) {
  for (final req in brd.requirements) {
    for (final state in place(req, brd).boundStates) {
      if (state.name == name) return true;
    }
  }
  return false;
}

