// Snippet extraction for the migration guides (Gate G4).
//
// Usage:
//   dart run tool/extract_snippets.dart            # generate
//   dart run tool/extract_snippets.dart --check    # fail if output differs
//
// Contract (Phase 7, G8): every ```dart block in
// `guide/MigratingFrom-*.md` either compiles against `cell_flutter` (it
// lands in the generated test) or is preceded on its own line by
// `<!-- skip-extraction -->` (illustrative "before" Riverpod/Bloc code
// and fragments that need app context).
//
// The generated file is `test/migration/_extracted_test.dart`:
// - Blocks containing `testWidgets(` / `test(` are emitted at top level
//   inside `main`.
// - Other blocks are wrapped in a plain `test()` body with the shared
//   import header.
// - Class declarations are hoisted to file scope (Dart has no local
//   classes) and deduplicated.
// - A fragment whose last code line is a bare expression statement gets
//   a terminating `;`.

import 'dart:io';

const _skipMarker = '<!-- skip-extraction -->';

const _header = '''
// GENERATED by tool/extract_snippets.dart — do not edit by hand.
// Re-generate with: dart run tool/extract_snippets.dart

// ignore_for_file: avoid_relative_lib_imports, unused_local_variable
// ignore_for_file: unused_element, unused_import, prefer_final_locals
// ignore_for_file: directives_ordering, no_leading_underscores_for_local_identifiers

import 'dart:async';

import 'package:cell_flutter/testing.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
''';

const _footer = '''
}
''';

class _Block {
  _Block(this.file, this.line, this.code);

  final String file;
  final int line;
  String code;
  bool skipped = false;
}

void main(List<String> args) {
  final check = args.contains('--check');
  final toolDir = File.fromUri(Platform.script).parent;
  final root = toolDir.parent;

  final guides = Directory('${root.path}${Platform.pathSeparator}guide')
      .listSync()
      .whereType<File>()
      // Gate G4 covers the two migration guides; extending the contract
      // to the HowTo guides is future work.
      .where((f) =>
          f.path.endsWith('.md') &&
          f.uri.pathSegments.last.startsWith('MigratingFrom-'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  final blocks = <_Block>[];
  for (final guide in guides) {
    final lines = guide.readAsLinesSync();
    for (var i = 0; i < lines.length; i++) {
      if (lines[i].trim() != '```dart') continue;
      final block = _Block(guide.uri.pathSegments.last, i + 1, '');
      block.skipped = i > 0 && lines[i - 1].trim() == _skipMarker;
      final body = <String>[];
      i++;
      while (i < lines.length && lines[i].trim() != '```') {
        body.add(lines[i]);
        i++;
      }
      block.code = body.join('\n');
      blocks.add(block);
    }
  }

  final out = StringBuffer(_header);
  final skipped = <String>[];
  final hoistedClasses = <String>[];
  for (final block in blocks) {
    if (block.skipped) {
      skipped.add('${block.file}:${block.line}');
      continue;
    }
    final name = '${block.file} line ${block.line}';
    if (block.code.contains('testWidgets(') || block.code.contains('test(')) {
      // Already a complete test declaration — emit at top level.
      out
        ..writeln(block.code)
        ..writeln();
      continue;
    }

    // Dart has no local class declarations: hoist any class in the
    // block to file scope before emitting the wrapped body.
    var body = block.code;
    final lines = body.split('\n');
    var classStart = -1;
    var classEnd = -1;
    for (var j = 0; j < lines.length; j++) {
      if (RegExp(r'^class\s').hasMatch(lines[j])) classStart = j;
      if (classStart >= 0 && lines[j].trim() == '}' && j > classStart) {
        classEnd = j;
        break;
      }
    }
    if (classStart >= 0 && classEnd >= 0) {
      final classText = lines.sublist(classStart, classEnd + 1).join('\n');
      if (!hoistedClasses.contains(classText)) {
        hoistedClasses.add(classText);
      }
      body = [
        ...lines.take(classStart),
        ...lines.skip(classEnd + 1),
      ].join('\n').trim();
    }

    // Fragments that end on a closing paren are expression statements
    // in guide context; terminate the last code line so the test body
    // parses (trailing comments stay as comments).
    final bodyLines = body.split('\n');
    var lastCode = bodyLines.length - 1;
    while (lastCode >= 0 &&
        (bodyLines[lastCode].trim().isEmpty ||
            bodyLines[lastCode].trimLeft().startsWith('//'))) {
      lastCode--;
    }
    if (lastCode >= 0) {
      final trimmed = bodyLines[lastCode].trimRight();
      if (!trimmed.endsWith(';') &&
          !trimmed.endsWith('}') &&
          !trimmed.endsWith('>')) {
        bodyLines[lastCode] = '$trimmed;';
      }
    }

    out
      ..writeln("  test('$name', () {")
      ..writeln(bodyLines.join('\n'))
      ..writeln('  });')
      ..writeln();
  }
  out.write(_footer);

  // Insert hoisted classes between the imports and `void main() {`.
  if (hoistedClasses.isNotEmpty) {
    final text = out.toString();
    final mainIndex = text.indexOf('\nvoid main() {');
    out
      ..clear()
      ..write(text.substring(0, mainIndex + 1))
      ..writeln(hoistedClasses.join('\n\n'))
      ..write(text.substring(mainIndex + 1));
  }

  final target = File('${root.path}${Platform.pathSeparator}test'
      '${Platform.pathSeparator}migration'
      '${Platform.pathSeparator}_extracted_test.dart');
  if (check) {
    if (!target.existsSync() || target.readAsStringSync() != out.toString()) {
      stderr.writeln('CHECK FAILED: test/migration/_extracted_test.dart is '
          'stale. Run: dart run tool/extract_snippets.dart');
      exitCode = 1;
      return;
    }
    stdout.writeln('CHECK PASSED: extracted snippets are up to date '
        '(${blocks.length} blocks, ${skipped.length} skipped).');
    return;
  }

  target.writeAsStringSync(out.toString());
  stdout.writeln('Wrote ${target.path}: ${blocks.length} dart blocks '
      '(${skipped.length} skipped, '
      '${blocks.length - skipped.length} extracted).');
  if (skipped.isNotEmpty) {
    stdout.writeln('Skipped (illustrative): ${skipped.join(', ')}');
  }
}
