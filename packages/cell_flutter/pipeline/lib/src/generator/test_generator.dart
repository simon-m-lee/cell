/// Generates `test/app_test.dart` for [brd].
GeneratedFile generateTests(Brd brd, Walkthrough walkthrough) {
  final buffer = StringBuffer()
    ..writeln('// Generated by mitose_flutter. Do not edit by hand —')
    ..writeln('// re-run the pipeline and review the diff instead.')
    ..writeln('// ignore_for_file: non_constant_identifier_names, '
        'unnecessary_import')
    ..writeln()
    ..writeln("import 'package:cell_flutter/testing.dart';")
    ..writeln("import 'package:flutter/material.dart';")
    ..writeln("import 'package:flutter_test/flutter_test.dart';")
    ..writeln();
  for (final screen in brd.requirements.map((r) => r.screen).toSet()) {
    buffer.writeln(
        "import 'package:${packageName(brd.title)}/screens/${screenFileName(screen)}';");
  }
  for (final cell in brd.state.where((s) => s.appLevel)) {
    buffer.writeln(
        "import 'package:${packageName(brd.title)}/cells/${cellFileName(cell.name)}';");
  }
  buffer
    ..writeln()
    ..writeln(
        '/// The pipeline LEDGER sink. Every requirement writes one line.')
    ..writeln('void LEDGER(String requirement, String evidence) {}')
    ..writeln()
    ..writeln('void main() {');

  for (final req in brd.requirements) {
    final choice = place(req, brd);
    final template = choice.pattern.toTestTemplate(req);
    final rawSetup = choice.extra['testSetup'] as String?;
    var setup =
        (rawSetup == null || rawSetup.isEmpty) ? template.setup : rawSetup;
    setup = _normalizeSetup(setup, choice);
    setup = _ensureScreenCells(setup, brd, req.screen);
    final pump = _pumpFor(req, brd);
    final interaction =
        choice.extra['testInteraction'] as String? ?? template.interaction;
    final assertion =
        choice.extra['testAssertion'] as String? ?? template.assertion;
    setup = _pruneUnusedDeclarations(setup, '$pump\n$interaction\n$assertion');
    final ledger = choice.extra['ledger'] as String? ?? template.ledger;

    buffer.writeln(
        "  testWidgets('${req.id} — ${req.sentence}', (tester) async {");
    if (setup.isNotEmpty) {
      for (final line in setup.split('\n')) {
        buffer.writeln('    $line');
      }
      if (!setup.endsWith('\n') || !setup.contains('\n')) {
        buffer.writeln();
      }
    }
    for (final line in pump.split('\n')) {
      buffer.writeln('    $line');
    }
    if (interaction.isNotEmpty) {
      for (final line in interaction.split('\n')) {
        if (line.isNotEmpty) buffer.writeln('    $line');
      }
    }
    for (final line in assertion.split('\n')) {
      buffer.writeln('    $line');
    }
    buffer
      ..writeln('    $ledger')
      ..writeln('  });')
      ..writeln();
  }

  buffer.writeln('}');
  return GeneratedFile(path: 'test/app_test.dart', content: buffer.toString());
}

String _pumpFor(BrdRequirement req, Brd brd) {
  final cells = screenCells(brd, req.screen)
      .map((s) =>
          s.restorable ? '#${s.name}: ${s.name}' : '#${s.name}: ${s.name}.cell')
      .join(', ');
  return 'await tester.pumpWithCells(\n'
      '  cells: {$cells},\n'
      '  child: const ${req.screen}Screen(),\n'
      ');';
}

/// Every cell the generated screen resolves from the scope: screen-local
/// states plus the app-level states its requirements bind.
List<BrdState> screenCells(Brd brd, String screen) {
  final used = <String>{};
  for (final req in brd.requirements.where((r) => r.screen == screen)) {
    for (final state in place(req, brd).boundStates) {
      used.add(state.name);
    }
  }
  return [
    ...screenLocalStates(brd, screen),
    for (final name in used)
      if (brd.stateByName(name) case final state? when state.appLevel) state,
  ];
}

/// The screen-local states for [screen] — mirrors the code generator's
/// owned-states rule (unbound states land on the first screen).
List<BrdState> screenLocalStates(Brd brd, String screen) {
  final isFirstScreen = brd.screens.first.name == screen;
  final bound = <String>{};
  for (final req in brd.requirements.where((r) => r.screen == screen)) {
    for (final state in place(req, brd).boundStates) {
      bound.add(state.name);
    }
  }
  final boundAnywhere = <String>{};
  for (final req in brd.requirements) {
    for (final state in place(req, brd).boundStates) {
      boundAnywhere.add(state.name);
    }
  }
  return [
    for (final state in brd.state)
      if (!state.appLevel &&
          (bound.contains(state.name) ||
              (isFirstScreen && !boundAnywhere.contains(state.name))))
        state,
  ];
}

/// Declares any screen-local cell the pump needs but the setup missed.
String _ensureScreenCells(String setup, Brd brd, String screen) {
  final buffer = StringBuffer();
  for (final state in screenCells(brd, screen)) {
    if (setup.contains('final ${state.name} =')) continue;
    if (state.restorable) {
      buffer.writeln('final ${state.name} = restorableState<${state.type}>(');
      buffer.writeln("  restorationId: '${state.name}',");
      buffer.writeln('  initial: ${normalizedInitial(state)},');
      buffer.writeln(');');
    } else {
      buffer.writeln(
          'final ${state.name} = Cell.state<${state.type}>(initial: ${normalizedInitial(state)});');
    }
  }
  if (buffer.isEmpty) return setup;
  return '$setup${setup.endsWith('\n') ? '' : '\n'}${buffer.toString()}';
}

/// Rewrites `Cell.state` test declarations into `restorableState` for
/// restorable states (RestorableCell IS a ValueCell — used directly),
/// and normalizes raw initials like `AsyncValue.loading` into the
/// cell's type (`SearchResult(AsyncValue.loading())`).
String _normalizeSetup(String setup, WidgetChoice choice) {
  var result = setup;
  for (final state in choice.boundStates.where((s) => s.restorable)) {
    final cellStatePattern = RegExp(
      'final ${state.name} = Cell\\.state<${_escape(state.type)}>'
      '\\(initial: (.*?)\\);',
      multiLine: true,
    );
    result = result.replaceAllMapped(cellStatePattern, (match) {
      return 'final ${state.name} = restorableState<${state.type}>(\n'
          "  restorationId: '${state.name}',\n"
          '  initial: ${match.group(1)},\n'
          ');';
    });
  }
  for (final state in choice.boundStates) {
    final initial = state.initial;
    if (initial == null) continue;
    final normalized = normalizedInitial(state);
    if (normalized != initial) {
      result = result.replaceAll(
        'initial: $initial',
        'initial: $normalized',
      );
    }
  }
  return result;
}

String _escape(String type) => type.replaceAll(
    RegExp(r'([\\<>\\(\\)\\[\\]\\{\\}\\.\\*\\+\\?\\|])'), r'\$1');

/// Drops declarations the test body never references (e.g. an app-level
/// auth cell when the screen uses the imported top-level cell).
String _pruneUnusedDeclarations(String setup, String body) {
  final lines = setup.split('\n');
  final kept = <String>[];
  for (var i = 0; i < lines.length; i++) {
    final line = lines[i];
    final match = RegExp(r'^\s*final (\w+) =').firstMatch(line);
    if (match != null) {
      final name = match.group(1)!;
      var block = line;
      var j = i;
      while (j < lines.length - 1 && !block.trimRight().endsWith(');')) {
        j++;
        block = '$block\n${lines[j]}';
      }
      final used =
          RegExp('(?<![A-Za-z0-9_])$name(?![A-Za-z0-9_])').hasMatch(body);
      if (!used) {
        i = j; // Skip the whole declaration block.
        continue;
      }
    }
    kept.add(line);
  }
  return kept.join('\n');
}
